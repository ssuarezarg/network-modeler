"""Write the model into a Git repository and commit only what changed.

Git already hashes content, so this keeps no hashes of its own: files are
written, and `git status` is asked what moved. Three things need care beyond
that.

**Provenance must not be written unconditionally.** `meta.yaml` carries
`collected_at` and `row_id`, which change on every capture whether or not the
device did. Writing it every run would dirty all 46 devices nightly and produce
a daily commit containing no actual change - exactly the churn this project
exists to prevent, reintroduced in its last stage. So `meta.yaml` is rewritten
only when the content beside it changed, which also makes its `collected_at`
mean the right thing: *when the configuration we are holding was captured*, not
when we last looked.

**A rename must move, not delete and re-add.** Devices are identified by
`device_id`; the hostname is only a path. When a device turns up under a new
name, `git mv` keeps its history attached instead of showing one device deleted
and another born.

**Deletion has to be defended against.** A device absent from the database might
be decommissioned - or the collector might have broken. Deletions are therefore
only considered on a complete, unfiltered run, and a run that would delete an
implausible share of the estate refuses instead. A collector outage must not be
able to empty the mirror.
"""
from __future__ import annotations

import subprocess
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .layout import ROOT

# A complete run that wants to remove more than this share of the mirror is
# assumed to be reacting to a broken collector rather than to decommissioning.
MAX_DELETION_SHARE = 0.10

REPORTS = "reports"

README = """# Network configuration mirror

Generated by [netconfig-mirror](https://bitbucket.org/bcmonenc/dt_model). Do not
edit by hand: every file here is rewritten from the collector database, and a
manual change will be overwritten on the next run.

## Layout

    inventory/<site>/<device>/device.yaml   structured model
    inventory/<site>/<device>/raw.cfg       redacted configuration, verbatim
    inventory/<site>/<device>/meta.yaml     provenance and coverage
    reports/freshness.md                    devices that stopped being captured

## Reading the history

The value here is the diff. `git log -p -- inventory/<site>/<device>/` shows
every change to one device over time, and who to ask about it.

## Secrets

Credential values are replaced before anything is written. A value shown as
`[OMITTED_BY_SANITIZER]` was masked upstream by the collector's sync; one shown
as `<redacted:...>` was replaced here by a keyed token, stable for an unchanged
credential so it produces no diff.

**This repository is still sensitive and must stay private.** Redaction removes
credentials, not identity: hostnames, IP addressing and VRF names remain, and
they describe the customer's topology.
"""


class GitError(RuntimeError):
    pass


@dataclass
class SyncReport:
    written: list[str] = field(default_factory=list)
    changed: list[str] = field(default_factory=list)
    renamed: list[tuple[str, str]] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    committed: str | None = None
    pushed: bool = False


class MirrorRepo:
    def __init__(self, path: str | Path):
        self.path = Path(path).resolve()

    # ---- git plumbing ----------------------------------------------------

    def _git(self, *args: str, check: bool = True) -> str:
        result = subprocess.run(
            ["git", *args], cwd=self.path, capture_output=True, text=True)
        if check and result.returncode != 0:
            raise GitError(f"git {' '.join(args)} failed: "
                           f"{result.stderr.strip() or result.stdout.strip()}")
        return result.stdout

    def ensure_ready(self) -> None:
        if not self.path.is_dir():
            raise GitError(
                f"{self.path} does not exist.\n"
                f"Clone the mirror repository there first, or create it with:\n"
                f"  git init {self.path}")
        if not (self.path / ".git").exists():
            raise GitError(
                f"{self.path} is not a Git repository.\n"
                f"  git init {self.path}\n"
                f"The mirror needs to be a repository: its whole value is the history.")

        # Uncommitted work here is almost certainly someone editing by hand, and
        # this run would overwrite it silently.
        dirty = self._git("status", "--porcelain").strip()
        if dirty:
            raise GitError(
                f"{self.path} has uncommitted changes. Commit or discard them "
                f"first — this run would overwrite them.\n{dirty[:400]}")

    # ---- reading current state -------------------------------------------

    def existing_devices(self) -> dict[str, str]:
        """device_id -> repository-relative directory, read from the repo itself.

        Deliberately derived from the committed files rather than from a
        separate index: an index is one more thing that can disagree with
        reality, and the repository already knows what it contains.
        """
        found: dict[str, str] = {}
        for meta_path in sorted((self.path / ROOT).glob("*/*/meta.yaml")):
            try:
                meta = yaml.safe_load(meta_path.read_text(encoding="utf-8")) or {}
            except yaml.YAMLError:
                continue
            device_id = (meta.get("source") or {}).get("device_id")
            if device_id:
                found[str(device_id)] = str(meta_path.parent.relative_to(self.path))
        return found

    # ---- writing ---------------------------------------------------------

    def move(self, old_relative: str, new_relative: str) -> None:
        target = self.path / new_relative
        target.parent.mkdir(parents=True, exist_ok=True)
        self._git("mv", old_relative, new_relative)

    def write_content(self, relative: str, device_yaml: str, raw_cfg: str) -> bool:
        """Write the content files. Returns True if either differs from HEAD."""
        directory = self.path / relative
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "device.yaml").write_text(device_yaml, encoding="utf-8")
        (directory / "raw.cfg").write_text(raw_cfg, encoding="utf-8")

        status = self._git("status", "--porcelain", "--",
                           f"{relative}/device.yaml", f"{relative}/raw.cfg")
        return bool(status.strip())

    def write_files(self, relative: str, files: dict[str, str]) -> bool:
        """Write several files into one device directory.

        Returns True if any of them differ from HEAD. Used for platforms whose
        configuration is several documents rather than one — the same
        content-versus-provenance split as `write_content`, so the metadata is
        only rewritten when something real moved.
        """
        directory = self.path / relative
        directory.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            (directory / name).write_text(content, encoding="utf-8")

        paths = [f"{relative}/{name}" for name in files]
        return bool(self._git("status", "--porcelain", "--", *paths).strip())

    def write_meta(self, relative: str, meta_yaml: str) -> None:
        (self.path / relative / "meta.yaml").write_text(meta_yaml, encoding="utf-8")

    def write_report(self, name: str, content: str) -> None:
        directory = self.path / REPORTS
        directory.mkdir(parents=True, exist_ok=True)
        (directory / name).write_text(content, encoding="utf-8")

    def ensure_readme(self) -> None:
        readme = self.path / "README.md"
        if not readme.exists():
            readme.write_text(README, encoding="utf-8")

    def remove(self, relative: str) -> None:
        self._git("rm", "-r", "--quiet", relative)

    def prune(self, keep_relative: set[str], *, complete_run: bool) -> list[str]:
        """Remove devices no longer in the database.

        Only on a complete run, and never a landslide: a collector that stopped
        reporting looks exactly like a mass decommissioning, and the mirror must
        not be emptiable by an upstream outage.
        """
        if not complete_run:
            return []

        present = {str(p.parent.relative_to(self.path))
                   for p in (self.path / ROOT).glob("*/*/meta.yaml")}
        stale = sorted(present - keep_relative)
        if not stale:
            return []

        share = len(stale) / max(len(present), 1)
        if share > MAX_DELETION_SHARE:
            raise GitError(
                f"Refusing to remove {len(stale)} of {len(present)} devices "
                f"({share:.0%}). A collector that stopped reporting looks like a "
                f"mass decommissioning; this is almost certainly an upstream "
                f"outage.\nIf it is genuine, remove them by hand and commit.")

        for relative in stale:
            self.remove(relative)
        return stale

    # ---- committing ------------------------------------------------------

    def commit(self, message: str, *, author: str | None = None) -> str | None:
        """Stage everything and commit. Returns the hash, or None if nothing
        changed - the normal outcome on a network that did not change."""
        self._git("add", "-A")
        if not self._git("diff", "--cached", "--name-only").strip():
            return None

        args = ["commit", "-q", "-m", message]
        if author:
            args += ["--author", author]
        self._git(*args)
        return self._git("rev-parse", "--short", "HEAD").strip()

    def push_needed(self, remote: str = "origin", branch: str | None = None) -> bool:
        """Whether the local branch holds commits the remote does not.

        Asked instead of assuming, so that a push which failed on an earlier run
        is retried on the next one rather than being stranded.
        """
        branch = branch or self._git("rev-parse", "--abbrev-ref", "HEAD").strip()
        # An unknown remote branch means there is certainly something to send.
        try:
            self._git("rev-parse", "--verify", f"{remote}/{branch}")
        except GitError:
            return True
        ahead = self._git("rev-list", "--count", f"{remote}/{branch}..{branch}").strip()
        return ahead not in ("", "0")

    def push(self, remote: str = "origin", branch: str | None = None) -> None:
        branch = branch or self._git("rev-parse", "--abbrev-ref", "HEAD").strip()
        self._git("push", remote, branch)


def build_message(report: SyncReport, *, sites: list[str] | None = None) -> str:
    """A subject that says what happened, and a body listing it."""
    parts: list[str] = []
    if report.changed:
        parts.append(f"{len(report.changed)} changed")
    if report.renamed:
        parts.append(f"{len(report.renamed)} renamed")
    if report.removed:
        parts.append(f"{len(report.removed)} removed")
    summary = ", ".join(parts) or "no device changes"

    scope = f" ({', '.join(sorted(sites))})" if sites else ""
    lines = [f"sync: {summary}{scope}", ""]

    for relative in sorted(report.changed):
        lines.append(f"changed  {relative}")
    for old, new in sorted(report.renamed):
        lines.append(f"renamed  {old} -> {new}")
    for relative in sorted(report.removed):
        lines.append(f"removed  {relative}")

    return "\n".join(lines).rstrip() + "\n"
